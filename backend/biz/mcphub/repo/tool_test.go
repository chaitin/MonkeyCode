func TestReplaceByUpstreamRollback(t *testing.T) {
	for _, failure := range []string{"schema", "create", "delete"} {
		t.Run(failure, func(t *testing.T) {
			client := openToolTestClient(t)
			ctx := context.Background()
			id := uuid.New()
			client.MCPUpstream.Create().SetID(id).SetName("test").SetSlug("test").SetScope("platform").SetType("server").SetURL("https://example.com/mcp").SaveX(ctx)
			r := NewToolRepo(client)
			input := func(name, desc string) UpsertToolInput {
				return UpsertToolInput{UpstreamID: id, Name: name, NamespacedName: name, Scope: "platform", Description: desc, InputSchema: json.RawMessage(`{}`)}
			}
			if err := r.ReplaceByUpstream(ctx, id, []UpsertToolInput{input("kept", "old"), input("stale", "old")}); err != nil {
				t.Fatal(err)
			}
			before := client.MCPTool.Query().Where(mcptool.NamespacedName("kept")).OnlyX(ctx)
			rows := []UpsertToolInput{input("kept", "new"), input("added", "new")}
			if failure == "schema" {
				rows[1].InputSchema = json.RawMessage(`{`)
			} else {
				client.MCPTool.Use(func(next ent.Mutator) ent.Mutator {
					return ent.MutateFunc(func(ctx context.Context, m ent.Mutation) (ent.Value, error) {
						_, deleting := m.Field("deleted_at")
						if (failure == "create" && m.Op().Is(ent.OpCreate)) || (failure == "delete" && deleting) {
							return nil, errors.New("injected write failure")
						}
						return next.Mutate(ctx, m)
					})
				})
			}
			if err := r.ReplaceByUpstream(ctx, id, rows); err == nil {
				t.Fatal("expected replacement failure")
			}
			after := client.MCPTool.GetX(ctx, before.ID)
			if after.Description != "old" || !after.SyncedAt.Equal(*before.SyncedAt) {
				t.Fatalf("earlier update was not rolled back: %+v", after)
			}
			if got := client.MCPTool.Query().CountX(ctx); got != 2 {
				t.Fatalf("got %d tools after rollback, want 2", got)
			}
			if client.MCPTool.Query().Where(mcptool.NamespacedName("added")).ExistX(entx.SkipSoftDelete(ctx)) {
				t.Fatal("new tool survived rollback")
			}
		})
	}
}

func TestReplaceByUpstreamRestoresAndDeletes(t *testing.T) {
	client := openToolTestClient(t)
	ctx := context.Background()
	id := uuid.New()
	client.MCPUpstream.Create().SetID(id).SetName("test").SetSlug("test").SetScope("platform").SetType("server").SetURL("https://example.com/mcp").SaveX(ctx)
	seed := func(name string) *db.MCPTool {
		return client.MCPTool.Create().SetUpstreamID(id).SetName(name).SetNamespacedName(name).SetScope("platform").SetInputSchema(map[string]any{}).SetVersionHash("old").SetSyncedAt(time.Now()).SaveX(ctx)
	}
	restored, stale := seed("restored"), seed("stale")
	client.MCPTool.DeleteOneID(restored.ID).ExecX(ctx)
	rows := []UpsertToolInput{{UpstreamID: id, Name: "restored", NamespacedName: "restored", Scope: "platform", VersionHash: "new", InputSchema: json.RawMessage(`{}`)}, {UpstreamID: id, Name: "added", NamespacedName: "added", Scope: "platform", InputSchema: json.RawMessage(`{}`)}}
	if err := NewToolRepo(client).ReplaceByUpstream(ctx, id, rows); err != nil {
		t.Fatal(err)
	}
	if got := client.MCPTool.GetX(ctx, restored.ID); got.VersionHash != "new" || !got.DeletedAt.IsZero() {
		t.Fatalf("restored tool = %+v", got)
	}
	if client.MCPTool.Query().Where(mcptool.ID(stale.ID)).ExistX(ctx) {
		t.Fatal("stale tool remained published")
	}
	if got := client.MCPTool.GetX(entx.SkipSoftDelete(ctx), stale.ID); got.DeletedAt.IsZero() {
		t.Fatal("stale tool was not soft deleted")
	}
	if got := client.MCPTool.Query().CountX(ctx); got != 2 {
		t.Fatalf("got %d published tools, want 2", got)
	}
}

func openToolTestClient(t *testing.T) *db.Client {
	t.Helper()
	client := enttest.Open(t, "sqlite3", fmt.Sprintf("file:replace-%s?mode=memory&cache=shared&_fk=1", uuid.NewString()))
	t.Cleanup(func() { client.Close() })
	// Production IDs are generated by PostgreSQL's UUID default. SQLite does
	// not implement that default, so supply IDs in the test client instead.
	client.MCPTool.Use(func(next ent.Mutator) ent.Mutator {
		return ent.MutateFunc(func(ctx context.Context, m ent.Mutation) (ent.Value, error) {
			if m.Op().Is(ent.OpCreate) {
				m.(*db.MCPToolMutation).SetID(uuid.New())
			}
			return next.Mutate(ctx, m)
		})
	})
	return client
}
